def get_tables_summary(db: Session) -> List[TableSummary]:
    """List summary information for all 16 core tables."""
    tables: List[TableSummary] = []

    for tbl in CORE_TABLES:
        meta = TABLE_METADATA.get(tbl, {"description": "", "category": "General"})
        # Row count
        row_cnt = db.execute(text(f"SELECT count(*) FROM {tbl};")).scalar() or 0

        # Column count
        col_cnt = db.execute(text("""
            SELECT count(*) 
            FROM information_schema.columns 
            WHERE table_schema = 'public' AND table_name = :tbl;
        """), {"tbl": tbl}).scalar() or 0

        # Primary key column
        pk_res = db.execute(text("""
            SELECT kcu.column_name
            FROM information_schema.table_constraints tc
            JOIN information_schema.key_column_usage kcu
              ON tc.constraint_name = kcu.constraint_name
              AND tc.table_schema = kcu.table_schema
            WHERE tc.constraint_type = 'PRIMARY KEY'
              AND tc.table_schema = 'public'
              AND tc.table_name = :tbl;
        """), {"tbl": tbl}).scalar() or "id"

        # Foreign keys count
        fk_cnt = db.execute(text("""
            SELECT count(*)
            FROM information_schema.table_constraints
            WHERE constraint_type = 'FOREIGN KEY'
              AND table_schema = 'public'
              AND table_name = :tbl;
        """), {"tbl": tbl}).scalar() or 0

        # Index count
        idx_cnt = db.execute(text("""
            SELECT count(*)
            FROM pg_indexes
            WHERE schemaname = 'public' AND tablename = :tbl;
        """), {"tbl": tbl}).scalar() or 0

        tables.append(TableSummary(
            name=tbl,
            description=meta["description"],
            row_count=row_cnt,
            column_count=col_cnt,
            primary_key=pk_res,
            foreign_key_count=fk_cnt,
            index_count=idx_cnt,
            category=meta["category"],
        ))

    return tables


