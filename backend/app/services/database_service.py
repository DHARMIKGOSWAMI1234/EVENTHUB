def _mask_sensitive_dict(d: Dict[str, Any]) -> Dict[str, Any]:
    """Masks sensitive fields like password_hash, qr_token, etc."""
    masked = {}
    for k, v in d.items():
        if k in ("password_hash", "token_hash", "qr_token"):
            masked[k] = "[PROTECTED]"
        elif k in ("phone",) and v:
            # Mask middle digits of phone
            val = str(v)
            if len(val) >= 7:
                masked[k] = val[:3] + "****" + val[-3:]
            else:
                masked[k] = "[PROTECTED]"
        elif k in ("email",) and v:
            parts = str(v).split("@")
            if len(parts) == 2:
                name, domain = parts
                masked[k] = (name[:2] + "***@" + domain) if len(name) > 2 else v
            else:
                masked[k] = v
        else:
            masked[k] = v
    return masked


