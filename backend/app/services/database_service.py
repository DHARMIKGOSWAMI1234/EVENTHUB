def execute_predefined_query(db: Session, query_key: str) -> Optional[QueryShowcaseItem]:
    """Safely executes an allowlisted DBMS query card and returns the output."""
    match = next((q for q in QUERY_CATALOG if q["key"] == query_key), None)
    if not match:
        return None

    sql_to_run = match["sql"]
    # If it's a multi-statement transaction or row locking demo, run the inner SELECT for demonstration
    if match["key"] == "transaction_demo":
        sql_to_run = "SELECT count(*) AS active_bookings_before FROM bookings WHERE status = 'CONFIRMED';"
    elif match["key"] == "row_locking_demo":
        sql_to_run = "SELECT id, event_id, status FROM event_seats WHERE event_id = 2 AND status = 'AVAILABLE' LIMIT 1;"

    start_time = time.perf_counter()
    rows_data: List[Dict[str, Any]] = []
    columns: List[str] = []

    try:
        res = db.execute(text(sql_to_run)).mappings().all()
        elapsed_ms = round((time.perf_counter() - start_time) * 1000, 2)
        if res:
            columns = list(res[0].keys())
            for r in res[:10]:
                rows_data.append(_mask_sensitive_dict(dict(r)))
    except Exception as e:
        elapsed_ms = round((time.perf_counter() - start_time) * 1000, 2)
        rows_data = [{"error": f"Execution notice: {str(e)}"}]

    return QueryShowcaseItem(
        key=match["key"],
        title=match["title"],
        category=match["category"],
        concept=match["concept"],
        purpose=match["purpose"],
        sql=match["sql"],
        columns=columns,
        sample_rows=rows_data,
        execution_time_ms=elapsed_ms,
        row_count=len(rows_data),
    )


